def sheet():
    src = Image.open(SRC)
    out = Image.new("P", (48, 32), 0)
    for f in range(3):
        for y in range(32):
            for x in range(16):
                c = src.getpixel((16 * f + x, y))
                row = OVER[f].get(y)
                if row and row[x] != ".":
                    c = int(row[x], 16)
                out.putpixel((16 * f + x, y), c)
    out.putpalette([v for c in PAL for v in c])
    return out


