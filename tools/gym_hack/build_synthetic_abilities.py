#!/usr/bin/env python3
"""Pokémon Canvas: the synthetic abilities (tools/gym_hack/synthetic_abilities.txt) into the game.

    python3 tools/gym_hack/build_synthetic_abilities.py

Checks every line (the species exist, the ability exists), gives each form that isn't listed its
species' first form's, and reports any Pokémon left without one. Writes:
  src/data/pokemon/synthetic_abilities.h    gSpeciesSyntheticAbilities[] (GetSpeciesSyntheticAbility)
  build/synthetic_abilities.json            for the Pokédex PDF and the review list
Needs one `make firered` first (the dex builder reads the preprocessed data)."""
import json
import re
import sys
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/gym_hack/guide"))
import build_dex as bd  # noqa: E402

SRC = ROOT / "tools/gym_hack/synthetic_abilities.txt"
OUT_H = ROOT / "src/data/pokemon/synthetic_abilities.h"
OUT_JSON = ROOT / "build/synthetic_abilities.json"


def parse():
    out = OrderedDict()
    for n, line in enumerate(SRC.read_text().splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = [p.strip() for p in line.split(" : ", 2)]
        if len(parts) < 2:
            raise SystemExit(f"{SRC.name}:{n}: expected 'SPECIES ... : Ability : why'")
        why = parts[2] if len(parts) > 2 else ""
        for sp in parts[0].split():
            key = "SPECIES_" + sp
            if key in out:
                raise SystemExit(f"{SRC.name}:{n}: {sp} is listed twice")
            out[key] = (parts[1], why, n)
    return out


def main():
    data = bd.load()
    names = data["abilities"]                       # ABILITY_X -> name
    by_name = {v.lower(): k for k, v in names.items() if v}
    dexnums = bd.national_dex()
    infos = OrderedDict()
    for key, body in data["species"].items():
        if key in ("SPECIES_NONE", "SPECIES_EGG"):
            continue
        info = bd.parse_species(key, body, data)
        if not info["dex"]:
            continue
        info["dex_num"] = dexnums.get(info["dex"], 0)
        if info["dex_num"]:
            infos[key] = info
    assigned = parse()
    errors = []
    for key, (ab, why, n) in assigned.items():
        if key not in infos:
            errors.append(f"line {n}: no species {key}")
        if ab.lower() not in by_name:
            errors.append(f"line {n}: no ability '{ab}'")
    if errors:
        raise SystemExit("\n".join(errors))
    # every form: its own line, or its species' first form's (megas and other battle-only forms
    # use their own abilities in battle: none)
    first = {}
    for k, info in infos.items():
        if not info["mega"]:
            first.setdefault(info["dex_num"], k)
    result, missing = OrderedDict(), []
    for k, info in infos.items():
        if info["mega"]:
            continue
        src = k if k in assigned else first[info["dex_num"]]
        if src not in assigned:
            missing.append(k)
            continue
        ab, why, _ = assigned[src]
        result[k] = {"ability": by_name[ab.lower()], "name": names[by_name[ab.lower()]], "why": why,
                     "from": src, "dex": info["dex_num"], "species": info["name"], "types": info["types"],
                     "own": [names.get(a, a) for a in info["abilities"] if a != "ABILITY_NONE"],
                     "own_keys": [a for a in info["abilities"] if a != "ABILITY_NONE"]}
    if missing:
        raise SystemExit("no synthetic ability: " + ", ".join(missing))
    same = [k for k, r in result.items() if r["ability"] in r["own_keys"]]
    if same:
        print("note: the synthetic ability is one it already has:", ", ".join(s[8:] for s in same))
    lines = ["// Pokémon Canvas: each species' synthetic ability (the Ability Synthesizer)",
             "// Generated by tools/gym_hack/build_synthetic_abilities.py from",
             "// tools/gym_hack/synthetic_abilities.txt - edit that and rerun, not this.", "",
             "const u16 gSpeciesSyntheticAbilities[NUM_SPECIES] =", "{"]
    for k, r in result.items():
        lines.append(f"    [{k}] = {r['ability']},")
    lines += ["};", ""]
    OUT_H.write_text("\n".join(lines))
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(result, ensure_ascii=False, indent=1))
    used = sorted({r["name"] for r in result.values()})
    print(f"{len(result)} species and forms, {len(assigned)} listed, {len(used)} different abilities")


if __name__ == "__main__":
    main()
