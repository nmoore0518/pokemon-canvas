#!/usr/bin/env python3
"""Pikachu's Beach (Pokémon Canvas, src/surfing_minigame.c): Yellow's surfing minigame graphics and
tilemaps, from the pret/pokeyellow disassembly (gfx/surfing_pikachu/), for the GBA.

    python3 tools/gym_hack/surfing_minigame_gfx.py PATH_TO_POKEYELLOW

Each Game Boy picture is a run of 8x8 tiles; here each becomes a 128-pixel-wide sheet (16 tiles a
row, in the same order, so a tile's number stays its number), its pixels the Game Boy's colour
numbers (0 white .. 3 black) as palette indices:
  graphics/surfing_minigame/bg.png     surfing_pikachu_1a (the course, the status bar, the letters)
  graphics/surfing_minigame/obj.png    surfing_pikachu_1b (Pikachu, splashes, banners, digits)
  graphics/surfing_minigame/intro.png  surfing_pikachu_1c (the title screen's)
and src/data/surfing_minigame_tilemaps.h (the title, beach and results tilemaps).
"""
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "graphics/surfing_minigame"
PAL = [(255, 255, 255), (255, 255, 0), (88, 184, 255), (24, 24, 24)] + [(0, 0, 0)] * 12


def tiles(path):
    im = Image.open(path).convert("L")
    w, h = im.size[0] // 8, im.size[1] // 8
    out = []
    for ty in range(h):
        for tx in range(w):
            out.append([[3 - im.getpixel((tx * 8 + x, ty * 8 + y)) // 85 for x in range(8)] for y in range(8)])
    return out


def sheet(ts, path):
    rows = (len(ts) + 15) // 16
    im = Image.new("P", (128, rows * 8), 0)
    im.putpalette([v for c in PAL for v in c] + [0] * (768 - 48))
    for i, t in enumerate(ts):
        for y in range(8):
            for x in range(8):
                im.putpixel(((i % 16) * 8 + x, (i // 16) * 8 + y), t[y][x])
    im.save(path)
    return len(ts)


def main(yellow):
    g = Path(yellow) / "gfx/surfing_pikachu"
    OUT.mkdir(parents=True, exist_ok=True)
    n = [sheet(tiles(g / f"surfing_pikachu_{k}.png"), OUT / f"{name}.png")
         for k, name in (("1a", "bg"), ("1b", "obj"), ("1c", "intro"))]
    lines = ["// Generated by tools/gym_hack/surfing_minigame_gfx.py from pret/pokeyellow's gfx/surfing_pikachu",
             f"// (bg {n[0]} tiles, obj {n[1]}, intro {n[2]})", ""]
    for name in ("beach_intro", "beach_outro", "title", "use_control_pad", "to_surf_rad"):
        data = (g / f"{name}.tilemap").read_bytes()
        cname = "sTilemap_" + "".join(p.capitalize() for p in name.split("_"))
        lines.append(f"static const u8 {cname}[{len(data)}] = {{")
        for i in range(0, len(data), 20):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
        lines.append("};")
    (ROOT / "src/data/surfing_minigame_tilemaps.h").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
