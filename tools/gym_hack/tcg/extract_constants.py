#!/usr/bin/env python3
"""Pokémon Canvas: the Trading Card Game duel's constants, from pret/poketcg (src/constants/*.asm),
so the duel (src/tcg/) can follow the game's own code closely: the same duel variables at the same
offsets (DUELVARS_*, a 256-byte page per duelist), statuses, card locations, flags...

    python3 tools/gym_hack/tcg/extract_constants.py <path to a pret/poketcg checkout>

Writes include/constants/tcg.h (every name prefixed TCG_).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = Path(sys.argv[1]) / "src"
FILES = ["card_data_constants.asm", "duel_constants.asm", "deck_ai_constants.asm", "duel_interface_constants.asm",
         "text_constants.asm", "attack_animation_constants.asm",
         "animation_constants.asm", "sfx_constants.asm", "music_constants.asm", "menu_constants.asm",
         "sprite_constants.asm", "palette_constants.asm"]


def num(tok):
    tok = tok.strip()
    if tok.startswith("$"):
        return f"0x{tok[1:]}"
    if tok.startswith("%"):
        return f"0b{tok[1:]}"
    return tok


def expr(e, known):
    e = e.split(";")[0].strip()
    e = re.sub(r"\$([0-9A-Fa-f]+)", r"0x\1", e)
    e = re.sub(r"%([01]+)", r"0b\1", e)
    e = re.sub(r"\b([A-Z][A-Z0-9_]*)\b", lambda m: ("TCG_" + m[1]) if m[1] in known else m[1], e)
    return e


def main():
    out = ["// Generated by tools/gym_hack/tcg/extract_constants.py from pret/poketcg's constants: the",
           "// Trading Card Game's own names and values (prefixed TCG_), for Pokémon Canvas's duel (src/tcg/)",
           "#ifndef GUARD_CONSTANTS_TCG_H", "#define GUARD_CONSTANTS_TCG_H", ""]
    known = set()
    for f in FILES:
        p = SRC / "constants" / f
        if not p.exists():
            continue
        out.append(f"// ---- {f}")
        cval, cstep = 0, 1
        for line in p.read_text().splitlines():
            s = line.strip()
            m = re.match(r"const_def\s*(.*)", s)
            if m:
                args = [a.strip() for a in m[1].split(";")[0].split(",") if a.strip()]
                cval = expr(args[0], known) if args else "0"
                cstep = expr(args[1], known) if len(args) > 1 else "1"
                cval = f"({cval})"
                continue
            m = re.match(r"const_skip\b\s*([^;]*)", s)
            if m:
                n = m[1].strip() or "1"
                cval = f"({cval} + ({n}) * ({cstep}))"
                continue
            m = re.match(r"const_next\s+([^;]+)", s)
            if m:
                cval = f"({expr(m[1].strip(), known)})"
                continue
            m = re.match(r"const\s+(\w+)", s)
            if m:
                out.append(f"#define TCG_{m[1]} {cval}")
                known.add(m[1])
                cval = f"(TCG_{m[1]} + ({cstep}))"
                continue
            m = re.match(r"(?:DEF\s+)?(\w+)\s+EQUS\s+\"LOW\(w\w+\)\"\s*;\s*([0-9a-fA-F]{2})", s)
            if m:
                out.append(f"#define TCG_{m[1]} 0x{m[2]}")
                known.add(m[1])
                continue
            m = re.match(r"DEF\s+(\w+)\s+EQU\s+(.+)", s)
            if m and "EQUS" not in s:
                v = re.sub(r"\bconst_value\b", lambda _: str(cval), expr(m[2], known))
                if re.search(r"\b(LOW|HIGH|BANK|STRLEN|SIZEOF|DEF|STARTOF)\b|\bw[A-Z]", v):
                    continue
                out.append(f"#define TCG_{m[1]} ({v})")
                known.add(m[1])
                continue
            m = re.match(r"DEF\s+(\w+)\s+EQU\s+const_value", s)
            if m:
                out.append(f"#define TCG_{m[1]} {cval}")
                known.add(m[1])
        out.append("")
    out += ["#endif // GUARD_CONSTANTS_TCG_H", ""]
    (ROOT / "include/constants/tcg.h").write_text("\n".join(out))
    print(len(known), "constants")


if __name__ == "__main__":
    main()
