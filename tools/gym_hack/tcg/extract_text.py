#!/usr/bin/env python3
"""Pokémon Canvas: the Trading Card Game duel's text (prompts, results, effect messages), from the
pret/poketcg disassembly: every text its duel code (home/, engine/duel/) uses, in its own words.

    python3 tools/gym_hack/tcg/extract_text.py <path to a pret/poketcg checkout>

Writes include/constants/tcg_text.h (TCG_TEXT_*: the game's names) and src/data/tcg/text.h
(gTcgTexts[]): the texts in the game's own bytes (tcg_charmap.py: its charmaps and text macros),
for its text engine (TX_HALFWIDTH, TX_SYMBOL, TX_RAM1/2/3, TX_LINE...).
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from tcg_charmap import Charmaps, c_bytes, text_blocks  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
SRC = Path(sys.argv[1]) / "src"


def texts():
    cm = Charmaps(SRC)
    return {k: cm.encode_text_block(v) for k, v in text_blocks(SRC).items()}


def used(t):
    code = ""
    for d in ("home", "engine/duel", "engine/menus", "engine/gfx"):
        for f in sorted((SRC / d).rglob("*.asm")):
            code += f.read_text()
    words = set(re.findall(r"\b(\w+Text\w*)\b", code))
    return [k for k in t if k in words]


def tname(n):
    """the label without its "Text" (HandText_2: Hand_2, YourDiscardPileText2: YourDiscardPile2)"""
    return re.sub(r"Text(\w*)$", r"\1", n)


def main():
    t = texts()
    names = used(t)
    h = ["// Generated by tools/gym_hack/tcg/extract_text.py (from pret/poketcg): the duel's text",
         "#ifndef GUARD_CONSTANTS_TCG_TEXT_H", "#define GUARD_CONSTANTS_TCG_TEXT_H", "", "enum TcgText", "{",
         "    TCG_TEXT_NONE,"]
    h += [f"    TCG_TEXT_{tname(n)}," for n in names]
    h += ["    TCG_NUM_TEXTS,", "};", ""]
    # the text symbols (TX_SYMBOL's: constants/charmaps.asm's txsymbol), SYM_*
    cm = Charmaps(SRC)
    syms = sorted({(v[1], k[1:-1]) for k, v in cm.maps["main"].items() if len(v) == 2 and v[0] == 5})
    h += [f"#define TCG_SYM_{n} 0x{v:02X}" for v, n in syms]
    h += ["", "#endif // GUARD_CONSTANTS_TCG_TEXT_H", ""]
    (ROOT / "include/constants/tcg_text.h").write_text("\n".join(h))
    c = ["// Generated by tools/gym_hack/tcg/extract_text.py (from pret/poketcg): the duel's text, in the",
         "// game's own words and encoding (tools/gym_hack/tcg/tcg_charmap.py)", "",
         "const u8 *const gTcgTexts[TCG_NUM_TEXTS] =", "{", '    [TCG_TEXT_NONE] = (const u8 *)"",']
    c += [f"    [TCG_TEXT_{tname(n)}] = (const u8 *){c_bytes(t[n])}," for n in names]
    c += ["};", ""]
    (ROOT / "src/data/tcg/text.h").write_text("\n".join(c))
    print(len(names), "texts")


main()
