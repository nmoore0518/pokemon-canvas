#!/usr/bin/env python3
"""Pokémon Canvas: the Trading Card Game duel's text (prompts, results, effect messages), from the
pret/poketcg disassembly: every text its duel code (home/, engine/duel/) uses, in its own words.

    python3 tools/gym_hack/tcg/extract_text.py <path to a pret/poketcg checkout>

Writes include/constants/tcg_text.h (TCG_TEXT_*: the game's names) and src/data/tcg/text.h
(gTcgTexts[]). The game's text codes stay as tags in the strings: <RAMNAME> (a duelist's name),
<RAMTEXT> (the next of two texts: TcgUi's txRam2), <RAMNUM> (the next of two numbers: txRam3),
<FIRE>..<COLORLESS> (energy symbols); "\\n" a new line, "\\f" a new box (the game's two-line boxes).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = Path(sys.argv[1]) / "src"


def texts():
    t = {}
    for f in sorted((SRC / "text").glob("text*.asm")):
        cur, buf = None, []
        for line in f.read_text().splitlines():
            m = re.match(r"^(\w+):", line)
            if m:
                cur, buf = m[1], []
                continue
            if cur is None:
                continue
            s = line.strip()
            m = re.match(r'(text|line|textfw|linefw)\s+"(.*)"', s)
            if m:
                buf.append(("\n" if m[1].startswith("line") and buf else "") + m[2])
            elif s.startswith("done"):
                t[cur] = "".join(buf)
                cur = None
    return t


def used(t):
    code = ""
    for d in ("home", "engine/duel"):
        for f in sorted((SRC / d).rglob("*.asm")):
            code += f.read_text()
    words = set(re.findall(r"\b(\w+Text)\b", code))
    return [k for k in t if k in words]


def cstr(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("??", "?\\?")
    return '"' + s.replace("é", "\\x80").replace("”", '\\"').replace("“", '\\"') + '"'


def main():
    t = texts()
    names = used(t)
    h = ["// Generated by tools/gym_hack/tcg/extract_text.py (from pret/poketcg): the duel's text",
         "#ifndef GUARD_CONSTANTS_TCG_TEXT_H", "#define GUARD_CONSTANTS_TCG_TEXT_H", "", "enum TcgText", "{",
         "    TCG_TEXT_NONE,"]
    h += [f"    TCG_TEXT_{n[:-4]}," for n in names]
    h += ["    TCG_NUM_TEXTS,", "};", "", "#endif // GUARD_CONSTANTS_TCG_TEXT_H", ""]
    (ROOT / "include/constants/tcg_text.h").write_text("\n".join(h))
    c = ["// Generated by tools/gym_hack/tcg/extract_text.py (from pret/poketcg): the duel's text, in the",
         "// game's own words (tags: see the script)", "",
         "const u8 *const gTcgTexts[TCG_NUM_TEXTS] =", "{", '    [TCG_TEXT_NONE] = (const u8 *)"",']
    c += [f"    [TCG_TEXT_{n[:-4]}] = (const u8 *){cstr(t[n])}," for n in names]
    c += ["};", ""]
    (ROOT / "src/data/tcg/text.h").write_text("\n".join(c))
    print(len(names), "texts")


main()
