#!/usr/bin/env python3
"""Pokémon Canvas: the Trading Card Game duel's graphics, from the pret/poketcg disassembly, as the
game has them: Game Boy Color 2bpp/1bpp tiles (src/tcg/gbc.c draws them as the GBC did).

    python3 tools/gym_hack/tcg/extract_gfx.py <path to a pret/poketcg checkout>

Converts the PNGs as the disassembly's build does (rgbgfx --colors dmg: white 0 .. black 3; -x N
drops the last N tiles; the cards: column-major, their own palettes), and lays the data out as its
gfx.asm does, so offsets the game's code uses ("DuelOtherGraphics + $15 tiles") hold. Writes
include/constants/tcg_gfx.h (the offsets below) and src/data/tcg/gfx.h:
  gTcgFontsGfx[]      gfx.asm's "Gfx 1" and "Gfx 2" sections (FullWidthFonts .. DuelBoxMessages),
                      with TCG_GFX_OFFSET_<label> for each label
  gTcgCardGfx[][]     each card art (TcgGfxId, src/data/tcg/cards.h): $30 tiles, then its palette
"""
import fnmatch
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
SRC = Path(sys.argv[1]) / "src"


def make_flags():
    """the Makefile's per-file RGBGFXFLAGS: {png stem path: (trim, columns)}"""
    flags = {}
    mk = (SRC.parent / "Makefile").read_text()
    for path, fl in re.findall(r"^src/(gfx/\S+)\.[12]bpp: RGBGFXFLAGS \+= (.*)$", mk, re.M):
        flags[path] = fl
    return flags


FLAGS = make_flags()


def tiles(png, depth, columns=False):
    im = Image.open(SRC / png)
    w, h = im.size
    if im.mode == "P":
        idx = list(im.tobytes())    # (--colors embedded: the PNG's own palette order)
    else:
        px = list(im.convert("L").tobytes())
        if depth == 1:
            idx = [0 if v >= 128 else 1 for v in px]
        else:
            idx = [min(3, (255 - v + 42) // 85) for v in px]
    order = []
    tw, th = w // 8, h // 8
    if columns:
        order = [(tx, ty) for tx in range(tw) for ty in range(th)]
    else:
        order = [(tx, ty) for ty in range(th) for tx in range(tw)]
    out = []
    for tx, ty in order:
        t = []
        for y in range(8):
            lo = hi = 0
            for x in range(8):
                c = idx[(ty * 8 + y) * w + tx * 8 + x]
                lo |= (c & 1) << (7 - x)
                hi |= ((c >> 1) & 1) << (7 - x)
            t += [lo] if depth == 1 else [lo, hi]
        out.append(t)
    return out


def incbin(path):
    """the bytes rgbasm INCBINs for `path` (a .1bpp/.2bpp/.pal from its PNG)"""
    stem, ext = path.rsplit(".", 1)
    fl = " ".join(v for k, v in FLAGS.items() if fnmatch.fnmatch(stem, k.replace("%", "*")))
    if ext == "pal":
        im = Image.open(SRC / (stem + ".png"))
        pal = im.getpalette()[:12]
        out = []
        for i in range(4):
            r, g, b = (v >> 3 for v in pal[i * 3:i * 3 + 3])
            v = r | g << 5 | b << 10
            out += [v & 0xFF, v >> 8]
        return out
    t = tiles(stem + ".png", 1 if ext == "1bpp" else 2, "--columns" in fl)
    m = re.search(r"-x (\d+)", fl)
    if m:
        t = t[:len(t) - int(m[1])]
    return [b for tile in t for b in tile]


WANTED = {"Gfx 1", "Gfx 2"} | {f"Card Gfx {i}" for i in range(1, 12)}


def gfx_sections():
    """gfx.asm: [(label or None, [bytes])...] in order, per section"""
    out, cur = {}, None
    for line in (SRC / "gfx.asm").read_text().splitlines():
        s = line.split(";")[0].strip()
        m = re.match(r'SECTION "([^"]+)"', s)
        if m:
            cur = m[1]
            out[cur] = []
            continue
        m = re.match(r"(\w+)::", s)
        if m and cur:
            out[cur].append((m[1], []))
            continue
        m = re.match(r'INCBIN "([^"]+)"(?:,\s*(\$?\w+),\s*(\$?\w+))?', s)
        if m and cur:
            if not out[cur]:
                out[cur].append((None, []))
            if cur not in WANTED:
                continue
            data = incbin(m[1])
            if m[2]:
                off, n = int(m[2].lstrip("$"), 16), int(m[3].lstrip("$"), 16)
                data = data[off:off + n]
            out[cur][-1][1].extend(data)
    return out


def carray(name, data, per_line=32):
    lines = [f"const u8 {name}[{len(data)}] =", "{"]
    for i in range(0, len(data), per_line):
        lines.append("    " + ", ".join("0x%02X" % b for b in data[i:i + per_line]) + ",")
    lines.append("};")
    return lines


def main():
    sec = gfx_sections()
    out = ["// Generated by tools/gym_hack/tcg/extract_gfx.py (from pret/poketcg): the duel's graphics, as",
           "// the Game Boy Color game has them (2bpp/1bpp tiles; src/tcg/gbc.c draws them).", ""]
    # the fonts and duel graphics: "Gfx 1" and "Gfx 2", one block
    fonts, offs = [], []
    for s in ("Gfx 1", "Gfx 2"):
        for label, data in sec[s]:
            if label:
                offs.append((label, len(fonts)))
            fonts += data
    h = ["// Generated by tools/gym_hack/tcg/extract_gfx.py (from pret/poketcg): where gfx.asm's labels are",
         "// in gTcgFontsGfx (src/data/tcg/gfx.h)", "#ifndef GUARD_CONSTANTS_TCG_GFX_H", "#define GUARD_CONSTANTS_TCG_GFX_H", ""]
    h += [f"#define TCG_GFX_OFFSET_{label} 0x{off:04X}" for label, off in offs]
    h += ["", f"#define TCG_FONTS_GFX_SIZE {len(fonts)}", "#define TCG_CARD_GFX_SIZE (0x30 * 16 + 8)", "",
          "#endif // GUARD_CONSTANTS_TCG_GFX_H", ""]
    (ROOT / "include/constants/tcg_gfx.h").write_text("\n".join(h))
    out += carray("gTcgFontsGfx", fonts)
    out.append("")
    # the card art, in TcgGfxId's order
    gfx_ids = re.findall(r"^\s+TCG_GFX_(\w+),", (ROOT / "include/constants/tcg_cards.h").read_text(), re.M)
    gfx_ids = [g for g in gfx_ids if g != "NUM_GFX" and not g.startswith("OFFSET")]
    cards = {}
    for label, data in [e for i in range(1, 12) for e in sec[f"Card Gfx {i}"]]:
        if label and label.endswith("CardGfx"):
            cards[label[:-len("CardGfx")].upper()] = data
    out.append("const u8 gTcgCardGfx[TCG_NUM_GFX][TCG_CARD_GFX_SIZE] =")
    out.append("{")
    for g in gfx_ids:
        d = cards[g]
        assert len(d) == 0x30 * 16 + 8, (g, len(d))
        out.append(f"    [TCG_GFX_{g}] =")
        out.append("    {")
        for i in range(0, len(d), 32):
            out.append("        " + ", ".join("0x%02X" % b for b in d[i:i + 32]) + ",")
        out.append("    },")
    out.append("};")
    (ROOT / "src/data/tcg/gfx.h").write_text("\n".join(out) + "\n")
    print(len(fonts), "bytes of fonts and duel graphics,", len(gfx_ids), "card art")


main()
