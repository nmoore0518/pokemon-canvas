#!/usr/bin/env python3
"""The back room's Pokémon (Pokémon Canvas, src/pit_boss.c): which Pokémon are hard to find in
the wild. Every species in a wild table the player can reach (as the guide's encounter tables
work it out: tools/gym_hack/guide/build_encounters.py), with its best share of any one method's
encounters anywhere.

    python3 tools/gym_hack/build_pit_boss_pool.py

Writes src/data/pit_boss_pool.h: the wild species (sorted, for a binary search) and which of them
are rare (RARE_SHARE percent or less, everywhere). Re-run after changing the wild tables.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/gym_hack/guide"))
import build_encounters as be

RARE_SHARE = 5


def best_shares():
    groups = json.loads((ROOT / "data/maps/map_groups.json").read_text())
    maps, name_of = {}, {}
    for g in groups["group_order"]:
        for folder in groups[g]:
            j = json.loads((ROOT / f"data/maps/{folder}/map.json").read_text())
            maps[folder] = j
            name_of[j["id"]] = folder
    reach = be.reachable_maps(maps, name_of)
    pools = {}
    for p in json.loads((ROOT / "src/data/exotic_safari_pools.json").read_text()):
        pools[(p["map"], p["species"][0])] = p["species"]
    best = {}

    def add(mapid, mons, rates):
        tab = {}
        for mon, r in zip(mons, rates):
            sp = mon["species"]
            if sp == "SPECIES_NONE":
                continue
            group = pools.get((mapid, sp), [sp])
            for s in group:
                tab[s] = tab.get(s, 0) + r / len(group)
        for s, share in tab.items():
            best[s] = max(best.get(s, 0), share)

    wj = json.loads((ROOT / "src/data/wild_encounters.json").read_text())
    for e in wj["wild_encounter_groups"][0]["encounters"]:
        if "FireRed" not in e["base_label"] or e["map"] not in reach:
            continue
        for f in ("land_mons", "water_mons", "rock_smash_mons"):
            if f in e:
                add(e["map"], e[f]["mons"], be.RATES[f])
        if "fishing_mons" in e:
            for _, start, rates in be.RODS:
                add(e["map"], e["fishing_mons"]["mons"][start:start + len(rates)], rates)
    return best


def main():
    best = best_shares()
    species = sorted(best)
    rare = [s for s in species if best[s] <= RARE_SHARE]
    out = ["// Generated by tools/gym_hack/build_pit_boss_pool.py. Don't edit by hand.",
           "// Every species found in the wild (the player's reach), and the rare ones: "
           f"{RARE_SHARE}% or less of a method's encounters, wherever they're found.",
           "",
           "static const u16 sWildSpecies[] =",
           "{"]
    out += [f"    {s}," for s in species]
    out += ["};", "", "static const u16 sRareWildSpecies[] =", "{"]
    out += [f"    {s}," for s in rare]
    out += ["};", ""]
    (ROOT / "src/data/pit_boss_pool.h").write_text("\n".join(out))
    print(f"{len(species)} wild species, {len(rare)} rare")


if __name__ == "__main__":
    main()
