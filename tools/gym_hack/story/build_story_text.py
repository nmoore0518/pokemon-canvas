#!/usr/bin/env python3
"""Pokémon Canvas: story dialogue (tools/gym_hack/story/*.txt) into data/text/*.inc, wrapped to the
message box by the game's own FONT_NORMAL glyph widths.

    python3 tools/gym_hack/story/build_story_text.py

Format (see dad_story.txt): `== Label` starts a text (`== Label [page]` for a full-page note), a line
with just `|` starts a new box or page; words wrap to two lines a box (seven a page)."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
BOX_WIDTH = 27 * 8 - 4          # the message box (what the tests check)
PAGE_WIDTH = 26 * 8 - 12        # a note page (src/note_page.c: 26 tiles, 6 px margins)
PAGE_LINES = 7
PLACEHOLDER_WIDTH = {"{PLAYER}": 7 * 7, "{RIVAL}": 7 * 7, "{STR_VAR_1}": 11 * 6, "{STR_VAR_2}": 11 * 6,
                     "{STR_VAR_3}": 11 * 6}


def glyph_widths():
    src = (ROOT / "src/fonts.c").read_text()
    body = src.split("gFontNormalLatinGlyphWidths[] = {", 1)[1].split("};", 1)[0]
    return [int(x) for x in re.findall(r"\d+", body)]


def charmap():
    table = {}
    for line in (ROOT / "charmap.txt").read_text(encoding="utf-8").splitlines():
        m = re.match(r"^'(.+?)'\s*=\s*([0-9A-Fa-f]{2})\s*$", line)
        if m:
            ch = m.group(1).encode().decode("unicode_escape") if m.group(1).startswith("\\") else m.group(1)
            if len(ch) == 1:
                table.setdefault(ch, int(m.group(2), 16))
    table.setdefault("é", table.get("é", 0x1B))
    return table


WIDTHS, CHARS = glyph_widths(), charmap()


def width(text):
    w = 0
    for ph, pw in PLACEHOLDER_WIDTH.items():
        n = text.count(ph)
        w += n * pw
        text = text.replace(ph, "")
    for ch in text:
        code = CHARS.get(ch)
        if code is None:
            raise SystemExit(f"no character {ch!r} in charmap ({text})")
        w += WIDTHS[code] if code < len(WIDTHS) else 8
    return w


def wrap(para, limit):
    lines, line = [], ""
    for word in para.split():
        trial = f"{line} {word}" if line else word
        if line and width(trial) > limit:
            lines.append(line)
            line = word
        else:
            line = trial
    if line:
        lines.append(line)
    return lines


def to_inc(label, boxes, page):
    """boxes: paragraphs. A box text: \\n between a box's two lines, \\p between boxes; a page:
    \\n between lines, \\p between pages."""
    out = [f"{label}::"]
    parts = []   # (line, separator before it)
    for b, para in enumerate(boxes):
        if page:   # each source line of a page starts a new line
            lines = [ln for src in para for ln in wrap(src, PAGE_WIDTH)]
        else:
            lines = wrap(" ".join(para), BOX_WIDTH)
        per = PAGE_LINES if page else 2
        if page and len(lines) > per:
            raise SystemExit(f"{label}: a page of {len(lines)} lines (max {per}): split it with |")
        for i, ln in enumerate(lines):
            if i == 0:
                sep = "" if b == 0 else "\\p"
            elif page:
                sep = "\\n"
            else:   # a long box scrolls on a line at a time
                sep = "\\n" if i == 1 else "\\l"
            parts.append((sep, ln))
    for i, (sep, ln) in enumerate(parts):
        nxt = parts[i + 1][0] if i + 1 < len(parts) else "$"
        ln = ln.replace('"', '\\"')
        out.append(f'\t.string "{ln}{nxt}"')
    return "\n".join(out) + "\n"


def build(src, dst):
    texts, cur = [], None
    for raw in src.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line.startswith("#") or (not line and cur is None):
            continue
        m = re.match(r"^== (\w+)( \[page\])?$", line)
        if m:
            cur = [m.group(1), bool(m.group(2)), [[]]]
            texts.append(cur)
        elif line == "|":
            cur[2].append([])
        elif line:
            cur[2][-1].append(line)
    out = [f"@ Generated by tools/gym_hack/story/build_story_text.py from {src.relative_to(ROOT)}: edit that.\n"]
    for label, page, boxes in texts:
        paras = [b for b in boxes if b]
        out.append(to_inc(label, paras, page))
    dst.write_text("\n".join(out), encoding="utf-8")
    return len(texts)


def main():
    for name in ("dad_story", "mentor_story"):
        n = build(ROOT / f"tools/gym_hack/story/{name}.txt", ROOT / f"data/text/{name}.inc")
        print(n, f"texts -> data/text/{name}.inc")


if __name__ == "__main__":
    main()
